// npm run check:skill: is skills/anticipator usable, and in step with the
// catalog? Regenerates into a temp dir and compares byte for byte, then
// checks the structure an agent relies on and runs the helper scripts.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { ROOT, loadCatalog } from "./lib.mjs";

const SKILL = path.join(ROOT, "skills", "anticipator");
let failures = 0;
const fail = (m) => { failures++; console.error(`  ✗ ${m}`); };
const ok = (m) => console.log(`  ✓ ${m}`);

function walk(dir, base = dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name), base) : [path.relative(base, path.join(dir, d.name))],
  ).sort();
}

// 1. In sync with the catalog (and generation is idempotent).
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "anticipator-skill-"));
execFileSync(process.execPath, ["--no-warnings=ExperimentalWarning", path.join(ROOT, "scripts", "generate-skill.mjs"), "--out", tmp], { stdio: "pipe" });
const a = walk(SKILL), b = walk(tmp);
if (JSON.stringify(a) !== JSON.stringify(b)) fail(`file list differs from a fresh generate (run npm run generate:skill)`);
else {
  const stale = a.filter((f) => fs.readFileSync(path.join(SKILL, f), "utf8") !== fs.readFileSync(path.join(tmp, f), "utf8"));
  if (stale.length) fail(`out of date: ${stale.join(", ")} (run npm run generate:skill)`);
  else ok(`in sync with catalog (${a.length} files, regenerated byte-identical)`);
}
fs.rmSync(tmp, { recursive: true, force: true });

// 2. Structure an agent relies on.
const md = fs.existsSync(path.join(SKILL, "SKILL.md")) ? fs.readFileSync(path.join(SKILL, "SKILL.md"), "utf8") : "";
const fm = /^---\nname: ([a-z0-9-]+)\ndescription: (.+)\n---\n/.exec(md);
if (!fm) fail("SKILL.md: missing frontmatter (name, description)");
else {
  ok(`SKILL.md frontmatter: name=${fm[1]}, description ${fm[2].length} chars`);
  if (fm[2].length > 1024) fail("SKILL.md description over 1024 chars");
}
for (const h of ["## When To Use", "## Workflow", "## Translation Rules"]) if (!md.includes(h)) fail(`SKILL.md: missing "${h}"`);
if (!/pixel-point\/animate-text/.test(md) || !/Alex Barashkov/.test(md)) fail("SKILL.md: credit to Pixel Point / Alex Barashkov missing");
else ok("credit to Pixel Point's animate-text present");
for (const f of ["references/schema.md", "references/selection-guide.md", "references/implementation-notes.md", "references/catalog.md", "assets/catalog.json", "scripts/list-specs.mjs", "scripts/get-spec.mjs", "scripts/runtime/phase.js"]) {
  if (!fs.existsSync(path.join(SKILL, f))) fail(`missing ${f}`);
}
const { catalog } = loadCatalog();
for (const id of catalog.visible_ids) {
  const f = path.join(SKILL, "assets", "specs", `${id}.json`);
  if (!fs.existsSync(f)) { fail(`missing assets/specs/${id}.json`); continue; }
  const s = JSON.parse(fs.readFileSync(f, "utf8"));
  if (s.enter.x_spring && !/^linear\(/.test(s.enter.x_css_linear || "")) fail(`${id}: enter.x_css_linear missing`);
}
ok(`${catalog.visible_ids.length} specs in assets/specs`);

// 3. The helper scripts run from anywhere and the runtime imports cleanly.
try {
  const list = execFileSync(process.execPath, [path.join(SKILL, "scripts", "list-specs.mjs")], { cwd: os.tmpdir() }).toString();
  if (list.trim().split("\n").length !== catalog.visible_ids.length) fail("list-specs: wrong row count");
  else ok("list-specs.mjs runs");
  const id = catalog.visible_ids[0];
  const portable = JSON.parse(execFileSync(process.execPath, [path.join(SKILL, "scripts", "get-spec.mjs"), id, "--portable"], { cwd: os.tmpdir() }).toString());
  if (JSON.stringify(portable).includes('"x_')) fail("get-spec --portable leaked x_* fields");
  else ok("get-spec.mjs --portable strips x_*");
  const { progressAt, phaseMs } = await import(path.join(SKILL, "scripts", "runtime", "phase.js"));
  const spec = JSON.parse(fs.readFileSync(path.join(SKILL, "assets", "specs", `${id}.json`), "utf8"));
  const end = progressAt(spec.enter, phaseMs(spec.enter));
  if (Math.abs(end - 1) > 1e-9) fail(`runtime: ${id} enter does not end at 1 (${end})`);
  else ok("scripts/runtime/phase.js imports and lands at 1");
} catch (e) {
  fail(`helper scripts: ${e.message}`);
}

if (failures) { console.error(`\n${failures} problem(s).`); process.exit(1); }
console.log("\nSkill OK.");
